test('network recovery and real-backend rejection of an invalid persisted token', async ({ page, request }) => {
  const value = await register(request);
  await signIn(page, value);
  await page.route('**/api/projects*', route => route.abort());
  await page.locator('.sidebar').getByRole('link', { name: 'Projects', exact: true }).click();
  // Force a fresh fetch rather than relying on the cached dashboard list.
  await page.reload();
  await expect(page.getByRole('alert').first()).toContainText('couldn’t connect');
  await page.unroute('**/api/projects*');
  await page.getByRole('button', { name: 'Try again', exact: true }).first().click();
  await expect(page.getByRole('heading', { name: 'No projects yet' })).toBeVisible();
  await page.evaluate(() => {
    const value = JSON.parse(localStorage.getItem('ismo.session')!);
    value.accessToken += 'invalid';
    localStorage.setItem('ismo.session', JSON.stringify(value));
  });
  await page.reload();
  await expect(page).toHaveURL(/\/login$/);
  await expect(page.getByText('Your session has expired. Please sign in to continue.')).toBeVisible();
  expect(await page.evaluate(() => localStorage.getItem('ismo.session'))).toBeNull();
});
test('keyboard dialogs, project movement, cascade deletion and scheduled session expiry', async ({ page, request }) => {
  const value = await register(request);
  await signIn(page, value);
  const session = await page.evaluate(() => JSON.parse(localStorage.getItem('ismo.session')!));
  const headers = { Authorization: 'Bearer ' + session.accessToken };
  const create = async (name: string) => {
    const result = await request.post('http://127.0.0.1:3001/api/projects', { headers, data: { name } });
    expect(result.status()).toBe(201);
    return (await result.json()).data;
  };
  const first = await create('First project');
  const second = await create('Second project');
  const created = await request.post('http://127.0.0.1:3001/api/tasks', { headers, data: { name: 'Move this task', projectId: first.id } });
  expect(created.status()).toBe(201);
  await page.goto('/projects/' + first.id);
  await page.getByRole('button', { name: 'Create a task', exact: true }).first().click();
  await expect(page.getByRole('dialog').getByLabel('Task name')).toBeFocused();
  await page.keyboard.press('Escape');
  await expect(page.getByRole('dialog')).not.toBeVisible();
  await expect(page.getByRole('button', { name: 'Create a task', exact: true }).first()).toBeFocused();
  await page.getByRole('button', { name: 'Edit Move this task', exact: true }).click();
  await page.getByRole('dialog').getByLabel('Project', { exact: true }).selectOption(second.id);
  await page.getByRole('dialog').getByRole('button', { name: 'Save changes' }).click();
  await expect(page.getByRole('heading', { name: 'No tasks yet' })).toBeVisible();
  await page.goto('/projects/' + second.id);
  await expect(page.locator('.task-main>strong')).toHaveText('Move this task');
  await page.getByRole('button', { name: 'Delete project', exact: true }).click();
  await page.getByRole('dialog').getByRole('button', { name: 'Delete project', exact: true }).click();
  const remaining = await request.get('http://127.0.0.1:3001/api/tasks', { headers });
  expect((await remaining.json()).data).toEqual([]);
  await page.evaluate(() => {
    const value = JSON.parse(localStorage.getItem('ismo.session')!);
    value.expiresAt = new Date(Date.now() + 5000).toISOString();
    localStorage.setItem('ismo.session', JSON.stringify(value));
  });
  await page.reload();
  await expect(page).toHaveURL(/\/login$/);
  await expect(page.getByText('Your session has expired. Please sign in to continue.')).toBeVisible();
});

test('sessions synchronize across tabs and expired saved sessions explain the redirect', async ({ page, context, request }) => {
  const value = await register(request);
  await signIn(page, value);
  const second = await context.newPage();
  await second.goto('/tasks');
  await expect(second.getByRole('heading', { name: 'Tasks', exact: false }).first()).toBeVisible();
  await page.getByRole('button', { name: 'Sign out', exact: true }).click();
  await expect(page).toHaveURL(/\/login$/);
  await expect(second).toHaveURL(/\/login$/);
  await signIn(second, value);
  await expect(page.getByTestId('metric-totalProjects')).toBeVisible();
  await page.close();
  await second.evaluate(() => {
    const saved = JSON.parse(localStorage.getItem('ismo.session')!);
    saved.expiresAt = new Date(Date.now() - 1000).toISOString();
    localStorage.setItem('ismo.session', JSON.stringify(saved));
  });
  await second.goto('/tasks');
  await expect(second).toHaveURL(/\/login$/);
  await expect(second.getByText('Your session has expired. Please sign in to continue.')).toBeVisible();
});
