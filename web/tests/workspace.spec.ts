const password = 'Test-password-42';
function email() { return 'web-' + Date.now() + '-' + Math.random().toString(16).slice(2) + '@example.test'; }
async function signIn(page: Page, value: string) {
  await page.goto('/login');
  await page.getByLabel('Email', { exact: true }).fill(value);
  await page.getByLabel('Password', { exact: true }).fill(password);
  await page.getByRole('button', { name: 'Sign in', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Dashboard', exact: false })).toBeVisible();
}
async function register(request: APIRequestContext) {
  const value = email();
  const response = await request.post('http://127.0.0.1:3001/api/auth/register', { data: { fullName: 'Web Test', email: value, password } });
  expect(response.status()).toBe(201);
  return value;
}
async function screenshot(page: Page, name: string) {
  await page.screenshot({ path: 'test-results/screenshots/' + name + '.png', fullPage: true });
}
